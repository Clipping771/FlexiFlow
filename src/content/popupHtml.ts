// Small HTML helpers shared by the reading card renderers: escaping, entity decoding and inline SVG icons.

export function isValidExampleTranslation(text?: string): boolean {
  if (!text) return false;
  const trimmed = text.trim();
  if (!trimmed) return false;
  const placeholders = [
    'উদাহরণ বাক্যের অর্থ',
    'উদাহরণ',
    'বাক্যে এর ব্যবহার।',
    'বাক্যটিতে এর ভাবার্থ স্পষ্টভাবে প্রকাশ পেয়েছে।'
  ];
  if (placeholders.includes(trimmed)) return false;
  if (/^Example sentence translated into/i.test(trimmed)) return false;
  return true;
}

export function decodeHtml(str?: string): string {
  if (!str) return '';
  return str
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#039;|&#39;|&apos;|&#x27;/g, "'")
    .replace(/&#(\d+);/g, (_, dec) => {
      try {
        const code = parseInt(dec, 10);
        return String.fromCharCode(code);
      } catch {
        return _;
      }
    })
    .replace(/&#x([0-9a-fA-F]+);/g, (_, hex) => {
      try {
        const code = parseInt(hex, 16);
        return String.fromCharCode(code);
      } catch {
        return _;
      }
    });
}

export function escapeHtml(str?: string): string {
  if (!str) return '';
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

